const el = (tag, cls, html) => { const e = document.createElement(tag); if (cls) e.className = cls; if (html != null) e.innerHTML = html; return e; };

let root = null;
let opened = false;

function build() {
  root = el('div', 'hidden');
  root.id = 'manual';
  root.innerHTML = `
    <div class="manual-dim"></div>
    <div class="manual-box">
      <div class="manual-head"><h2>📖 설명서</h2><button id="manual-close">닫기 <kbd>F1</kbd></button></div>
      <div class="manual-body">
        <nav class="manual-toc"></nav>
        <div class="manual-content"></div>
      </div>
    </div>`;
  document.body.append(root);
  root.querySelector('.manual-dim').onclick = closeManual;
  root.querySelector('#manual-close').onclick = closeManual;

  const toc = root.querySelector('.manual-toc');
  const content = root.querySelector('.manual-content');
  for (const s of SECTIONS) {
    const a = el('a', null, s.title);
    a.href = `#manual-${s.id}`;
    a.onclick = (e) => { e.preventDefault(); content.querySelector(`#manual-${s.id}`)?.scrollIntoView({ behavior: 'smooth', block: 'start' }); };
    toc.append(a);
    const sec = el('section', null, `<h3 id="manual-${s.id}">${s.title}</h3>${s.html}`);
    content.append(sec);
  }
}

export function openManual() {
  if (!root) build();
  root.classList.remove('hidden');
  opened = true;
}
export function closeManual() {
  if (root) root.classList.add('hidden');
  opened = false;
}
export function toggleManual() { (opened ? closeManual : openManual)(); }
export function isManualOpen() { return opened; }
